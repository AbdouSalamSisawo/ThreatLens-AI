import { useEffect, useState } from "react";
import { ArrowRight, BarChart3, Database, Gauge, Info } from "lucide-react";
import { Layout } from "../components/Layout";
import { api, ApiRequestError } from "../services/api";
import type { FullMetrics, ModelInfo } from "../types/api";
import { ErrorPanel } from "../components/ErrorPanel";

function Pct({ v }: { v: number | null | undefined }) {
  if (v == null) return <span className="font-mono text-text-faint">Not available</span>;
  return <span className="font-mono text-accent">{(v * 100).toFixed(2)}%</span>;
}

function Raw({ v, digits = 3 }: { v: number | null | undefined; digits?: number }) {
  if (v == null) return <span className="font-mono text-text-faint">Not available</span>;
  return <span className="font-mono text-accent">{v.toFixed(digits)}</span>;
}

function MetricCard({ label, value, expl }: { label: string; value: React.ReactNode; expl: string }) {
  return (
    <div className="panel p-5">
      <p className="text-[11px] font-medium uppercase tracking-wider text-text-faint">{label}</p>
      <p className="mt-1.5 text-2xl">{value}</p>
      <p className="mt-2 text-[11px] leading-relaxed text-text-dim">{expl}</p>
    </div>
  );
}

function ConfusionMatrix({ cm }: { cm: { tn: number; fp: number; fn: number; tp: number } }) {
  return (
    <div className="panel p-5">
      <h2 className="text-sm font-semibold text-text">Confusion matrix <span className="font-normal text-text-faint">(held-out test set)</span></h2>
      <div className="mt-4 grid grid-cols-[auto_1fr_1fr] gap-1.5 text-center text-xs">
        <div />
        <div className="text-text-faint">Predicted benign</div>
        <div className="text-text-faint">Predicted phishing</div>

        <div className="flex items-center justify-end pr-2 text-text-faint [writing-mode:vertical-rl]">Actually benign</div>
        <div className="rounded-md border border-ok/25 bg-ok/5 p-4">
          <p className="font-mono text-xl text-ok">{cm.tn}</p>
          <p className="mt-1 text-[11px] text-text-dim">true negatives</p>
        </div>
        <div className="rounded-md border border-warn/25 bg-warn/5 p-4">
          <p className="font-mono text-xl text-warn">{cm.fp}</p>
          <p className="mt-1 text-[11px] text-text-dim">false positives</p>
          <p className="text-[10px] text-text-faint">legitimate flagged as phishing</p>
        </div>

        <div className="flex items-center justify-end pr-2 text-text-faint [writing-mode:vertical-rl]">Actually phishing</div>
        <div className="rounded-md border border-danger/25 bg-danger/5 p-4">
          <p className="font-mono text-xl text-danger">{cm.fn}</p>
          <p className="mt-1 text-[11px] text-text-dim">false negatives</p>
          <p className="text-[10px] text-text-faint">phishing missed — false sense of safety</p>
        </div>
        <div className="rounded-md border border-accent/25 bg-accent/5 p-4">
          <p className="font-mono text-xl text-accent">{cm.tp}</p>
          <p className="mt-1 text-[11px] text-text-dim">true positives</p>
        </div>
      </div>
    </div>
  );
}

export function ModelPerformancePage() {
  const [metrics, setMetrics] = useState<FullMetrics | null>(null);
  const [info, setInfo] = useState<ModelInfo | null>(null);
  const [error, setError] = useState<ApiRequestError | null>(null);

  useEffect(() => {
    Promise.all([api.modelMetrics(), api.modelInfo()])
      .then(([m, i]) => {
        setMetrics(m);
        setInfo(i);
      })
      .catch((err) =>
        setError(
          err instanceof ApiRequestError
            ? err
            : new ApiRequestError("Failed to load model metrics.", "unknown", 0),
        ),
      );
  }, []);

  return (
    <Layout>
      <div className="border-b border-border">
        <div className="mx-auto max-w-6xl px-4 py-8 sm:px-6">
          <div className="flex items-center gap-3">
            <span className="panel flex h-11 w-11 items-center justify-center">
              <BarChart3 size={20} className="text-accent" aria-hidden />
            </span>
            <div>
              <h1 className="text-2xl font-semibold tracking-tight text-text">Model Performance</h1>
              <p className="text-sm text-text-dim">
                Genuine evaluation data generated by the training pipeline — never hand-written.
              </p>
            </div>
          </div>
        </div>
      </div>

      <div className="mx-auto max-w-6xl space-y-6 px-4 py-8 sm:px-6" aria-live="polite">
        {error && <ErrorPanel error={error} />}
        {!error && !metrics && (
          <div className="panel h-64 animate-pulse bg-surface-2/50" role="status" aria-label="Loading metrics" />
        )}
        {error?.code === "model_unavailable" && (
          <div className="panel p-6">
            <h2 className="text-sm font-semibold text-warn">Evaluation not available</h2>
            <p className="mt-2 text-sm leading-relaxed text-text-dim">
              No trained model artefacts were found on the server. This page
              displays only real evaluation output produced by{" "}
              the ML notebook in{" "}
              <span className="font-mono text-info">ml/notebooks/</span>.
              Run the notebook to train and deploy the model, then reload — nothing is fabricated here.
            </p>
          </div>
        )}

        {metrics && (
          <>
            {/* Identity */}
            <div className="panel p-5 sm:p-6">
              <div className="flex flex-wrap items-start justify-between gap-4">
                <div>
                  <h2 className="font-mono text-base text-text">{metrics.model_id}</h2>
                  <p className="mt-1 text-xs text-text-dim">
                    version <span className="font-mono text-text">v{metrics.model_version}</span> ·
                    trained {new Date(metrics.trained_at).toLocaleString()}
                  </p>
                </div>
                <span className="rounded-md border border-accent/30 bg-accent/10 px-3 py-1.5 text-xs font-medium text-accent">
                  {metrics.selected_model}
                </span>
              </div>
              <p className="mt-4 rounded-md border border-border bg-bg-deep p-3 text-xs leading-relaxed text-text-dim">
                <span className="font-medium text-text">Why this model: </span>
                {info?.selection_reason ?? metrics.selection_reason ?? "Not recorded."}
              </p>
            </div>

            {/* Dataset */}
            <div className="panel p-5 sm:p-6">
              <h2 className="flex items-center gap-2 text-sm font-semibold text-text">
                <Database size={15} className="text-accent" aria-hidden /> Training dataset
              </h2>
              <dl className="mt-4 grid gap-x-8 gap-y-3 text-xs sm:grid-cols-2 lg:grid-cols-4">
                <div>
                  <dt className="text-text-faint">Source</dt>
                  <dd className="mt-0.5 text-text">{metrics.dataset.source}</dd>
                </div>
                <div>
                  <dt className="text-text-faint">Retrieved</dt>
                  <dd className="mt-0.5 font-mono text-text">{metrics.dataset.retrieved}</dd>
                </div>
                <div>
                  <dt className="text-text-faint">Records used</dt>
                  <dd className="mt-0.5 font-mono text-text">{metrics.dataset.prepared_records.toLocaleString()}</dd>
                </div>
                <div>
                  <dt className="text-text-faint">Class distribution</dt>
                  <dd className="mt-0.5 font-mono text-text">
                    {metrics.dataset.class_distribution.phishing.toLocaleString()} phishing ·{" "}
                    {metrics.dataset.class_distribution.legitimate.toLocaleString()} legitimate
                  </dd>
                </div>
              </dl>
              <p className="mt-3 text-xs text-text-dim">
                Split: {String((info?.training_config as Record<string, unknown> | undefined)?.split ?? "60/20/20 stratified")} ·
                train {metrics.split_sizes.train} / validation {metrics.split_sizes.validation} / test{" "}
                {metrics.split_sizes.test} (fixed seed {String((info?.training_config as Record<string, unknown> | undefined)?.random_seed ?? "42")})
              </p>
            </div>

            {/* Test metrics */}
            {(info?.evaluation_available || ("accuracy" in metrics.test_metrics &&
              metrics.test_metrics.accuracy != null)) && (
              <>
                <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-4">
                  <MetricCard
                    label="Accuracy"
                    value={<Pct v={metrics.test_metrics.accuracy} />}
                    expl="Share of test URLs classified correctly at the 0.5 decision threshold."
                  />
                  <MetricCard
                    label="Precision"
                    value={<Pct v={metrics.test_metrics.precision} />}
                    expl="Of URLs flagged as phishing, how many truly were. Low precision means legitimate sites get flagged (annoying, erodes trust)."
                  />
                  <MetricCard
                    label="Recall"
                    value={<Pct v={metrics.test_metrics.recall} />}
                    expl="Of truly phishing URLs, how many were caught. Low recall is dangerous: missed phishing creates a false sense of safety."
                  />
                  <MetricCard
                    label="F1 score"
                    value={<Pct v={metrics.test_metrics.f1} />}
                    expl="Harmonic mean of precision and recall — a single balance point between the two failure modes."
                  />
                </div>

                <div className="grid gap-5 lg:grid-cols-2">
                  <ConfusionMatrix cm={metrics.test_metrics.confusion_matrix} />
                  <div className="space-y-5">
                    <div className="panel p-5">
                      <h2 className="flex items-center gap-2 text-sm font-semibold text-text">
                        <Gauge size={15} className="text-accent" aria-hidden /> Ranking quality
                      </h2>
                      <dl className="mt-4 space-y-3 text-xs">
                        <div className="flex items-center justify-between gap-4">
                          <dt className="text-text-dim">ROC-AUC</dt>
                          <dd><Raw v={metrics.test_metrics.roc_auc} /></dd>
                        </div>
                        <div className="flex items-center justify-between gap-4">
                          <dt className="text-text-dim">PR-AUC (average precision)</dt>
                          <dd><Raw v={metrics.test_metrics.pr_auc} /></dd>
                        </div>
                        <div className="flex items-center justify-between gap-4">
                          <dt className="text-text-dim">Majority-class baseline (validation acc.)</dt>
                          <dd><Raw v={metrics.majority_baseline_validation_accuracy} digits={4} /></dd>
                        </div>
                      </dl>
                      <p className="mt-3 text-[11px] leading-relaxed text-text-faint">
                        PR-AUC is emphasised because it is sensitive to the
                        phishing class; a trivial “always benign” predictor
                        would score near the baseline above.
                      </p>
                    </div>

                    <div className="panel p-5">
                      <h2 className="text-sm font-semibold text-text">Candidate comparison (validation set)</h2>
                      <table className="mt-4 w-full text-left text-xs">
                        <thead>
                          <tr className="text-text-faint">
                            <th scope="col" className="py-1.5 font-medium">Model</th>
                            <th scope="col" className="py-1.5 font-medium">PR-AUC</th>
                            <th scope="col" className="py-1.5 font-medium">F1</th>
                            <th scope="col" className="py-1.5 font-medium">Accuracy</th>
                          </tr>
                        </thead>
                        <tbody className="divide-y divide-border">
                          {Object.entries(metrics.validation_comparison).map(([name, m]) => (
                            <tr key={name} className={name === metrics.selected_model ? "text-accent" : "text-text-dim"}>
                              <td className="py-2 font-mono text-[11px]">
                                {name}{name === metrics.selected_model ? " ✓" : ""}
                              </td>
                              <td className="py-2 font-mono">{m.pr_auc?.toFixed(4)}</td>
                              <td className="py-2 font-mono">{m.f1.toFixed(4)}</td>
                              <td className="py-2 font-mono">{m.accuracy.toFixed(4)}</td>
                            </tr>
                          ))}
                        </tbody>
                      </table>
                    </div>
                  </div>
                </div>

                {/* Honesty checks */}
                <div className="panel p-5 sm:p-6">
                  <h2 className="flex items-center gap-2 text-sm font-semibold text-text">
                    <Info size={15} className="text-info" aria-hidden /> Generalisation honesty checks
                  </h2>
                  <div className="mt-4 grid gap-5 lg:grid-cols-2">
                    <div>
                      <h3 className="text-xs font-medium text-text">Domain-grouped split (stricter)</h3>
                      <p className="mt-1.5 text-[11px] leading-relaxed text-text-dim">
                        {metrics.domain_grouped_evaluation.description}
                      </p>
                      <dl className="mt-3 grid grid-cols-3 gap-2 text-center text-xs">
                        <div className="panel-inset px-2 py-2.5">
                          <dt className="text-[10px] text-text-faint">Accuracy</dt>
                          <dd className="mt-0.5 font-mono text-text">
                            {(metrics.domain_grouped_evaluation.metrics.accuracy * 100).toFixed(1)}%
                          </dd>
                        </div>
                        <div className="panel-inset px-2 py-2.5">
                          <dt className="text-[10px] text-text-faint">Recall</dt>
                          <dd className="mt-0.5 font-mono text-text">
                            {(metrics.domain_grouped_evaluation.metrics.recall * 100).toFixed(1)}%
                          </dd>
                        </div>
                        <div className="panel-inset px-2 py-2.5">
                          <dt className="text-[10px] text-text-faint">PR-AUC</dt>
                          <dd className="mt-0.5 font-mono text-text">
                            {metrics.domain_grouped_evaluation.metrics.pr_auc?.toFixed(3)}
                          </dd>
                        </div>
                      </dl>
                    </div>
                    <div>
                      <h3 className="text-xs font-medium text-text">Out-of-source probes</h3>
                      <ul className="mt-2 space-y-2.5 text-[11px] leading-relaxed text-text-dim">
                        {Object.entries(metrics.out_of_source_checks).map(([key, check]) => {
                          const c = check as { description?: string; n?: number; recall_proxy?: number; false_positive_rate?: number; flagged_as_phishing?: number };
                          return (
                            <li key={key} className="panel-inset p-3">
                              <p className="font-mono text-[10px] text-info">{key}</p>
                              {c.description && <p className="mt-1">{c.description}</p>}
                              <p className="mt-1 font-mono text-text">
                                {c.recall_proxy != null && `recall proxy: ${(c.recall_proxy * 100).toFixed(1)}% (${c.flagged_as_phishing}/${c.n})`}
                                {c.false_positive_rate != null && `FPR: ${(c.false_positive_rate * 100).toFixed(1)}% (${c.flagged_as_phishing}/${c.n})`}
                              </p>
                            </li>
                          );
                        })}
                      </ul>
                    </div>
                  </div>
                </div>
              </>
            )}

            {/* Limitations */}
            <div className="panel border-warn/25 p-5 sm:p-6">
              <h2 className="text-sm font-semibold text-warn">Evaluation limitations</h2>
              <ul className="mt-3 space-y-2">
                {metrics.evaluation_notes.map((n, i) => (
                  <li key={i} className="flex gap-2.5 text-xs leading-relaxed text-text-dim">
                    <ArrowRight size={13} className="mt-0.5 shrink-0 text-warn" aria-hidden />
                    {n}
                  </li>
                ))}
              </ul>
              <p className="mt-4 text-xs leading-relaxed text-text-dim">
                Results depend on dataset quality, class balance, the split
                strategy, and how closely the public corpus resembles real-world
                traffic. Random-split results must not be read as proof of
                real-world generalisation — that is exactly why the grouped and
                out-of-source checks are published alongside them.
              </p>
            </div>
          </>
        )}
      </div>
    </Layout>
  );
}
