"""GET /api/model-info - genuine model metadata and evaluation metrics."""

from __future__ import annotations

from fastapi import APIRouter, HTTPException, Request

from app.ml.model_metadata import public_model_info

router = APIRouter(prefix="/api", tags=["model"])


@router.get("/model-info")
def model_info(request: Request) -> dict:
    state = request.app.state
    if state.loaded_model is None:
        raise HTTPException(
            status_code=503,
            detail={
                "code": "model_unavailable",
                "message": state.model_error or "No trained model is loaded.",
            },
        )
    return public_model_info(state.loaded_model)


@router.get("/model-info/metrics")
def model_metrics(request: Request) -> dict:
    """Full machine-readable metrics file generated by the training pipeline."""
    state = request.app.state
    if state.loaded_model is None:
        raise HTTPException(
            status_code=503,
            detail={
                "code": "model_unavailable",
                "message": state.model_error or "No trained model is loaded.",
            },
        )
    return state.loaded_model.metrics
